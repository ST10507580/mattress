    private void mnuProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mnuProcessActionPerformed
        // TODO add your handling code here:
         String customer =txtCustomer.getText().trim();
            String product = (String)cmbProduct.getSelectedItem();
            
            if (customer.isEmpty()){
                JOptionPane.showMessageDialog(this, "Please enter the customer name.", "Validation", JOptionPane.WARNING_MESSAGE);
                return;
            }
            double price;
            try {
                price = Double.parseDouble(txtPrice.getText().trim());
                if (price <= 0){
                    throw new NumberFormatException();
                } 
            }catch (NumberFormatException ex){
                JOptionPane.showMessageDialog(this,"Please enter a valid price greater than 0.", "Validation", JOptionPane.WARNING_MESSAGE);
                return;
            }
            IProductCalculation calc = new ProductCalculations(price);
            double vat = calc.GetVat();
            double commission = calc.GetCommission();
            double total = calc.GetTotal();
            
            String message = "Customer Name: " + customer + "\n"
                    + "Product: " + product + "\n"
                    + "VAT: R" + vat + "\n"
                    + "COMMISSION: R" + commission + "\n"
                    + "TOTAL: R" + total ;
            
            JOptionPane.showMessageDialog(this, message, "Message", JOptionPane.INFORMATION_MESSAGE);
            saveToFile(customer, product, vat, commission, total);
            
        }
        
        private void saveToFile(String customer, String product, double vat, double commission, double total){
            try(PrintWriter out = new PrintWriter(new FileWriter("data.txt", true))){
                out.println("DATA LOG");
                
                out.println("************************");
                out.println("Product: " + product);
                out.println("VAT: R" + vat);
                out.println("COMMISSION: R" + commission);
                out.println("TOTAL: R" + total);
                
                out.println("******************************");
                out.println();
                
                
                
            }catch (IOException ex){
                JOptionPane.showMessageDialog(this,"Could not save to data.txt: " + ex.getMessage(),"File Error", JOptionPane.ERROR_MESSAGE);
            }
        
    }//GEN-LAST:event_mnuProcessActionPerformed

